export function skillById(id) {
  return SKILL_REGISTRY.find((skill) => skill.id === id) || null;
}

export function skillsForAgent(ids = []) {
  return ids.map((id) => skillById(id)).filter(Boolean).map((skill) => ({
    id: skill.id,
    description: skill.description,
    state: skill.state,
    enabled: false,
    permissions: [],
  }));
}
